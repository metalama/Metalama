using Metalama.Backstage;
using Metalama.Framework.ConfigurationFiles;
using Metalama.Tool.Divorce;
using Metalama.Tool.Introspection;
using Metalama.Tool.Preview;
using SharpCrafters.Aspects.Introspection.Query.Commands;
using SharpCrafters.Backstage.Commands;
using SharpCrafters.Backstage.Maintenance;
using Spectre.Console.Cli;
using System.Threading.Tasks;

namespace Metalama.Tool
{
    internal static class Program
    {
        private static async Task<int> Main( string[] args )
        {
            var app = new CommandApp();
            // The integrated development environments load the analyzers of Metalama, so the shutdown, kill and cleanup
            // commands report their processes, which the user has to close.
            var options = new BackstageCommandOptions(
                new ApplicationInfo(),
                MetalamaProduct.Instance,
                registerServices: builder => builder.AddDevelopmentEnvironmentShutdownStrategy() );
            options.AddConfigurationFileAdapter<UserDiagnosticsConfiguration>();
            options.AddConfigurationFileAdapter<TestRunnerOptions>();

            BackstageCommandFactory.ConfigureCommandApp(
                app,
                options,
                ConfigureMoreCommands );

            return await app.RunAsync( args );

            void ConfigureMoreCommands( IConfigurator config )
            {
                // Without an application name, Spectre.Console.Cli shows the name of the entry assembly file, metalama.dll,
                // in the usage line and in the examples.
                config.SetApplicationName( "metalama" );

                config.AddCommand<DivorceCommand>( "divorce" )
                    .WithData( options )
                    .WithDescription( "Copies code generated by Metalama back into your source code, in case you wanted to stop using Metalama." )
                    .WithExample( "divorce" )
                    .WithExample( "divorce", "--force" );

                config.AddCommand<PreviewCommand>( "preview" )
                    .WithData( options )
                    .WithDescription( "Shows the code that Metalama generates for some files of a project, formatted, without building the project." )
                    .WithExample( "preview", "src/Customer.cs" )
                    .WithExample( "preview", "src/Customer.cs", "src/Order.cs", "--framework", "net10.0", "--output", "obj/preview" );

                // The commands that query the introspection file (.mlsym) written by the last build.
                IntrospectionCommandFactory.AddIntrospectBranch( config, new IntrospectionCommandOptions( new MetalamaIntrospectionProvider() ) );

                // These root examples come after the ones of Backstage, which cover the license, config, telemetry and
                // cleanup commands.
                config.AddExample( "preview", "src/Customer.cs" );
                config.AddExample( "introspect", "show", "declaration", "src/Customer.cs:18" );
            }
        }
    }
}