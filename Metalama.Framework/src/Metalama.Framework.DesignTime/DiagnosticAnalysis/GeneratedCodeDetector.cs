using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Metalama.Framework.DesignTime.DiagnosticAnalysis;

/// <summary>
/// Determines whether Roslyn considers a syntax tree to be generated code, and therefore does not run the analyzers that
/// configure <see cref="GeneratedCodeAnalysisFlags.None"/> on it.
/// </summary>
/// <remarks>
/// <para>
/// Roslyn does not expose this decision for an arbitrary syntax tree, so this class applies the rules of Roslyn: the
/// <c>generated_code</c> option of <c>.editorconfig</c> when it is set, then the file name, then a comment that contains
/// <c>&lt;auto-generated</c> or <c>&lt;autogenerated</c> before the first token of the file.
/// </para>
/// <para>
/// The comment rule also accepts documentation comments. This is more than Roslyn requires, and it is deliberate: a caller
/// that skips a tree that Roslyn analyzes selects a later tree, whereas a caller that selects a tree that Roslyn skips
/// reports nothing.
/// </para>
/// </remarks>
internal static class GeneratedCodeDetector
{
    private static readonly string[] _generatedFileNameSuffixes = [".designer", ".generated", ".g", ".g.i"];

    /// <summary>
    /// Determines whether a syntax tree is generated code.
    /// </summary>
    /// <param name="syntaxTree">The syntax tree.</param>
    /// <param name="optionsProvider">The provider of the <c>.editorconfig</c> options, or <see langword="null"/> when no option is available.</param>
    /// <param name="cancellationToken">A cancellation token.</param>
    public static bool IsGeneratedCode( SyntaxTree syntaxTree, AnalyzerConfigOptionsProvider? optionsProvider, CancellationToken cancellationToken )
    {
        if ( optionsProvider != null
             && optionsProvider.GetOptions( syntaxTree ).TryGetValue( "generated_code", out var generatedCodeOption )
             && bool.TryParse( generatedCodeOption, out var isGeneratedCode ) )
        {
            return isGeneratedCode;
        }

        return HasGeneratedFileName( syntaxTree.FilePath ) || BeginsWithAutoGeneratedComment( syntaxTree, cancellationToken );
    }

    private static bool HasGeneratedFileName( string filePath )
    {
        if ( string.IsNullOrEmpty( filePath ) )
        {
            return false;
        }

        var fileName = Path.GetFileName( filePath );

        if ( fileName.StartsWith( "TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase ) )
        {
            return true;
        }

        var fileNameWithoutExtension = Path.GetFileNameWithoutExtension( fileName );

        return _generatedFileNameSuffixes.Any( suffix => fileNameWithoutExtension.EndsWith( suffix, StringComparison.OrdinalIgnoreCase ) );
    }

    private static bool BeginsWithAutoGeneratedComment( SyntaxTree syntaxTree, CancellationToken cancellationToken )
    {
        var root = syntaxTree.GetRoot( cancellationToken );

        if ( !root.HasLeadingTrivia )
        {
            return false;
        }

        foreach ( var trivia in root.GetLeadingTrivia() )
        {
            if ( !trivia.IsKind( SyntaxKind.SingleLineCommentTrivia )
                 && !trivia.IsKind( SyntaxKind.MultiLineCommentTrivia )
                 && !trivia.IsKind( SyntaxKind.SingleLineDocumentationCommentTrivia )
                 && !trivia.IsKind( SyntaxKind.MultiLineDocumentationCommentTrivia ) )
            {
                continue;
            }

            var text = trivia.ToFullString();

            if ( text.IndexOf( "<autogenerated", StringComparison.OrdinalIgnoreCase ) >= 0
                 || text.IndexOf( "<auto-generated", StringComparison.OrdinalIgnoreCase ) >= 0 )
            {
                return true;
            }
        }

        return false;
    }
}
